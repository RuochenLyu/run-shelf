#!/usr/bin/env ruby
# frozen_string_literal: true

require "json"

root = File.expand_path("..", __dir__)
output_path = File.join(root, "RunShelf/CLI/GeneratedSchemas.swift")
check_only = ARGV.delete("--check")
abort "Usage: scripts/generate_cli_schemas.rb [--check]" unless ARGV.empty?

schemas = {
  taskSpec: File.join(root, "schemas/task-spec.schema.json"),
  cliResult: File.join(root, "schemas/cli-result.schema.json")
}

rendered = schemas.map do |name, path|
  json = JSON.pretty_generate(JSON.parse(File.read(path))) + "\n"
  abort "Schema contains unsupported raw-string terminator: #{path}" if json.include?('"""#')
  "    static let #{name} = #\"\"\"\n#{json}\"\"\"#"
end.join("\n\n")

output = <<~SWIFT
  // Generated by scripts/generate_cli_schemas.rb. Do not edit.
  import Foundation

  enum GeneratedSchemas {
  #{rendered}
  }
SWIFT

if check_only
  abort "Generated schema source is out of date. Run scripts/generate_cli_schemas.rb." unless File.exist?(output_path) && File.read(output_path) == output
  puts "Generated CLI schemas are in sync."
else
  File.write(output_path, output)
  puts "Generated #{output_path.delete_prefix(root + "/")}"
end
